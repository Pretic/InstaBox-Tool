def render(report, output=print):
    def say(line):
        output("  " + line)
    config = report["config"]
    config_labels = {"ok": "部署记录与节点配置一致", "mismatch": "部署记录与节点配置不一致，未继续探测", "missing": "未找到完整节点配置", "error": "配置无法安全读取或格式无效", "unknown": "未确认"}
    say("本机配置： " + config_labels.get(config["status"], "未确认"))
    if config["status"] == "mismatch":
        labels = (("portMatches", "端口"), ("uuidMatches", "用户标识"), ("pathMatches", "连接路径"))
        say("一致检查： " + "；".join(label + ("一致" if config[key] else "不一致") for key, label in labels))
    def service_text(record):
        if record["status"] == "running":
            result = "运行中"
        elif record["status"] == "stopped":
            result = "当前未运行"
        else:
            result = "状态未读取或尚未稳定"
        if record.get("restarts") is not None:
            result += "；自动重启 " + str(record["restarts"]) + " 次"
        if record.get("exitStatus") not in (None, 0):
            result += "；最近退出码 " + str(record["exitStatus"])
        return result
    say("节点服务： " + service_text(report["nodeService"]))
    def probe_text(item):
        result = CODE_LABELS[item["code"]]
        if item.get("httpStatus") and item["httpStatus"] != 101:
            result += "（HTTP " + str(item["httpStatus"]) + "）"
        return result
    say("本机握手： " + probe_text(report["local"]))
    connector = report["connector"]
    say("隧道进程： " + service_text(connector))
    say("组件版本： " + (connector.get("version") or "未读取"))
    configured = {"auto": "自动选择", "http2": "HTTP/2（TCP）", "legacy-quic": "旧版默认 QUIC", "unknown": "未确认"}
    protocols = {"quic": "QUIC", "http2": "HTTP/2", None: "未记录"}
    say("启动设置： " + configured[connector["configuredProtocol"]] + "（下次启动生效）")
    say("日志协议： 初始 " + protocols[connector["initialProtocol"]] + "；最近注册 " + protocols[connector["registeredProtocol"]])
    say("注册记录： " + ("曾注册连接，仅作辅助证据" if connector["registered"] else "未发现注册记录"))
    domains = {"found": "已确认属于当前隧道进程", "missing": "尚未读取到临时地址", "changed": "当前地址变化，请重新检查", "error": "日志无法安全读取", "skipped": "本次跳过 Quick 公网链路", "unconfirmed": "已读取地址，但日志与当前进程的对应关系未确认"}
    say("临时域名： " + domains[report["domain"]["status"]])
    public_text = probe_text(report["public"])
    if report["public"].get("reason") == "local_only":
        public_text = "已跳过，本次只检查本机"
    elif report["public"].get("reason") == "fixed_only":
        public_text = "已跳过，当前仅使用固定隧道"
    elif report["public"].get("reason") == "no_current_domain":
        public_text = "已跳过，尚无可确认的当前 Quick 地址"
    elif report["public"].get("reason") == "unexpected_domain":
        public_text = "已跳过，待展示地址与当前地址不一致"
    say("公网握手： " + public_text)
    say("探测方式： 独立直连，不使用 HTTP(S) 代理环境")
    if report["proxyEnvironmentPresent"]:
        say("代理环境： 检测到代理变量，本次未使用其地址或凭据")
    if report["exitCode"] == 0:
        say("诊断结果： 本次已检查的 WebSocket 链路通过")
    elif report["exitCode"] == 2:
        say("诊断结果： 配置或诊断步骤尚待处理，未确认节点链路")
    else:
        say("诊断结果： 本次检查未完全通过，不能据此认定节点永久失效")
    say("验证范围： 仅 WebSocket 握手，未验证 VLESS 授权或代理出站")
    for label, message in ACTION_GUIDANCE[recommend(report)]:
        say(label + "： " + message)


class SafeParser(argparse.ArgumentParser):
    def error(self, message):
        raise ProbeError("arguments")


def main(args=None, *, probe=None, output=print):
    arguments = list(sys.argv[1:] if args is None else args)
    quiet = "--quiet" in arguments
    try:
        parser = SafeParser(description="InstaBox Tool WebSocket transport diagnostics; credentials are never displayed.")
        commands = parser.add_subparsers(dest="command")
        status = commands.add_parser("status")
        status.add_argument("--json", action="store_true")
        status.add_argument("--local-only", action="store_true")
        quick = commands.add_parser("check-quick")
        quick.add_argument("--quiet", action="store_true")
        quick.add_argument("--attempts", type=int, default=1)
        quick.add_argument("--timeout", type=float, default=8)
        quick.add_argument("--wait-seconds", type=float, default=0)
        quick.add_argument("--expect-host")
        # argparse help normally writes directly; --quiet also suppresses it.
        with contextlib.redirect_stdout(io.StringIO()) if quiet else contextlib.nullcontext():
            try:
                parsed = parser.parse_args(arguments or ["status"])
            except SystemExit as error:
                return error.code
        probe = probe or Probe()
        if parsed.command == "check-quick":
            if not 1 <= parsed.attempts <= 5 or not 1 <= parsed.timeout <= 15 or not 0 <= parsed.wait_seconds <= 60:
                raise ProbeError("arguments")
            if parsed.expect_host is not None and not HOST_RE.fullmatch(parsed.expect_host):
                raise ProbeError("arguments")
            report = probe.check_quick(attempts=parsed.attempts, timeout=parsed.timeout, expect_host=parsed.expect_host,
                                       wait_seconds=parsed.wait_seconds, progress=None if quiet else output)
        else:
            report = probe.diagnose(local_only=parsed.local_only)
        report["nextAction"] = recommend(report)
        if not quiet:
            if parsed.command == "status" and parsed.json:
                output(json.dumps(report, ensure_ascii=False, sort_keys=True))
            else:
                render(report, output)
        return report["exitCode"]
    except KeyboardInterrupt:
        if not quiet:
            output("  诊断已中断，未更改配置或服务。")
        return 130
    except ProbeError:
        if not quiet:
            output("  参数无效；使用 status [--json] [--local-only] 或 check-quick [--attempts 1..5] [--timeout 1..15] [--wait-seconds 0..60] [--quiet] [--expect-host 官方临时域名]。")
        return 2
    except Exception:
        if not quiet:
            output("  诊断未完成确认；未显示私有配置、日志或原始错误。")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
