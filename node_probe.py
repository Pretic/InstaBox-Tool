"""Read-only, credential-free diagnostics for the node's WebSocket transport.

A successful probe verifies RFC 6455 opening handshakes, not VLESS credentials
or proxy egress. Private paths/UUIDs, HTTP bodies and raw command/log output are
never part of a report. All network access is direct, without proxy discovery.
"""

